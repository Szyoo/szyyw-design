const SVG_NS = "http://www.w3.org/2000/svg";

/** 全部可用名字（现名，不含旧名别名） */
export const ICON_NAMES = Object.freeze(Object.keys(ICON_DATA));

function resolve(name) {
  const key = ICON_ALIASES[name] ?? name;
  const body = ICON_DATA[key];
  if (body === undefined) throw new Error(`@szyyw/design/icons: unknown icon "${name}"`);
  return { key, body };
}

/** 名字（含旧名别名）是否可用 */
export function hasIcon(name) {
  return (ICON_ALIASES[name] ?? name) in ICON_DATA;
}

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const len = (v) => (typeof v === "number" ? `${v}px` : v);

function attrsOf(name, opts = {}) {
  const { key } = resolve(name);
  const cls = ["icon", `icon-${key}`];
  if (opts.spin) cls.push("icon-spin");
  if (opts.className) cls.push(opts.className);
  const a = {
    xmlns: SVG_NS,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    "stroke-width": String(opts.strokeWidth ?? 2),
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
    class: cls.join(" ")
  };
  if (opts.size != null) a.style = `width:${len(opts.size)};height:${len(opts.size)}`;
  if (opts.label) { a.role = "img"; a["aria-label"] = opts.label; }
  else { a["aria-hidden"] = "true"; a.focusable = "false"; }
  return a;
}

/** SVG 标记字符串 */
export function iconSvg(name, opts) {
  const a = attrsOf(name, opts);
  const attrs = Object.entries(a).map(([k, v]) => `${k}="${esc(v)}"`).join(" ");
  return `<svg ${attrs}>${resolve(name).body}</svg>`;
}

/** SVG 元素（需要 DOM） */
export function icon(name, opts) {
  const tpl = document.createElement("template");
  tpl.innerHTML = iconSvg(name, opts);
  return /** @type {SVGSVGElement} */ (tpl.content.firstElementChild);
}

/**
 * 声明式：把 root 内的 `[data-icon]` 占位（如 `<i data-icon="x"></i>`）替换成 `<svg class="icon">`。
 * 占位上的 class 追加到 svg；aria-label 作为 label（无则装饰）；data-size / data-spin / data-stroke-width 照用。
 * 已替换的不会重复处理；返回替换个数。
 */
export function enhanceIcons(root = document) {
  let n = 0;
  for (const ph of root.querySelectorAll("[data-icon]:not(svg)")) {
    const d = ph.dataset;
    const size = d.size == null ? undefined : /^\d+(\.\d+)?$/.test(d.size) ? Number(d.size) : d.size;
    const svg = icon(d.icon, {
      size,
      label: ph.getAttribute("aria-label") || undefined,
      className: ph.getAttribute("class") || undefined,
      strokeWidth: d.strokeWidth ? Number(d.strokeWidth) : undefined,
      spin: d.spin != null && d.spin !== "false"
    });
    ph.replaceWith(svg);
    n++;
  }
  return n;
}
